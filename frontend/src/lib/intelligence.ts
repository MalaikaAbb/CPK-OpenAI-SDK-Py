import "server-only";

import type { AbstractAgent } from "@ag-ui/client";
import {
  CopilotKitIntelligence,
  CopilotRuntime,
} from "@copilotkit/runtime/v2";

/**
 * CopilotKit Intelligence for the two Threads routes (/api/threads).
 *
 * The runtime options are the Headless Threads page's `server.ts` block,
 * verbatim (marked below). The Threads Drawer page prints no runtime code; it
 * says the credential is server-side and names `CPK_INTELLIGENCE_API_KEY` for
 * cloud-hosted Intelligence — the same variable `server.ts` reads.
 *
 * Harness glue around it:
 *   - `agent` is undefined in `server.ts`; the route passes the Quickstart's
 *     agent (HttpAgent → backend /agent) in as a parameter.
 *   - `verifyAppSession` is undefined in `server.ts`; `verifyAppSession` below
 *     is a stub (there is no sign-in in the harness).
 *   - Without a key, `server.ts`'s `apiKey: process.env.CPK_INTELLIGENCE_API_KEY!`
 *     would build the client with `undefined`. The block's own comment
 *     describes the alternative — no `intelligence`, SSE mode, chat still
 *     works — so with no key the runtime is built without it, and the drawer
 *     shows its locked view instead of crashing.
 */

export const INTELLIGENCE_ENABLED = Boolean(process.env.CPK_INTELLIGENCE_API_KEY);

/**
 * Harness glue (stub): `server.ts` calls `verifyAppSession(request)` and
 * expects `{ user: { id, name } }`. No auth here, so everyone is one demo
 * user unless the request carries `x-user-id` / `x-user-name`.
 */
async function verifyAppSession(request: Request) {
  return {
    user: {
      id: request.headers.get("x-user-id") ?? "harness-demo-user",
      name: request.headers.get("x-user-name") ?? "Harness Demo User",
    },
  };
}

export function createThreadsRuntime(agent: AbstractAgent): CopilotRuntime {
  if (!INTELLIGENCE_ENABLED) {
    // harness glue: the documented no-`intelligence` fallback (see above)
    return new CopilotRuntime({ agents: { default: agent } });
  }

  // ── doc: Headless Threads prose block "server.ts" (verbatim; `agent` and
  //    `verifyAppSession` supplied above) ──
const runtime = new CopilotRuntime({
  agents: {
    default: agent,
  },
  // Without `intelligence` the runtime runs in SSE mode and the thread
  // UI has nothing to list — chat still works, so this fails quietly.
  intelligence: new CopilotKitIntelligence({
    apiKey: process.env.CPK_INTELLIGENCE_API_KEY!,
  }),
  // Required alongside `intelligence`: threads are scoped per user, so
  // without this every visitor shares one history. Resolve the real
  // signed-in user — see Thread & History Lifecycle.
  identifyUser: async (request) => {
    const session = await verifyAppSession(request);
    if (!session?.user) throw new Error("Unauthorized");
    return { id: session.user.id, name: session.user.name };
  },
  // Thread names are auto-generated by default.
  // Set to false to disable:
  // generateThreadNames: false,

  // Optional: tune thread lock behavior
  // lockTtlSeconds: 20,              // Lock TTL (default 20s, max 3600s)
  // lockHeartbeatIntervalSeconds: 15, // Heartbeat interval (default 15s, max 3000s)
  // lockKeyPrefix: "my-app",          // Custom Redis key prefix for the lock
});
  // ── end doc ──

  return runtime;
}
